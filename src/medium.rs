    /// Apply interference between new wavefront and existing medium.
    /// 
    /// Constructive interference boosts energy of phase-aligned wavefronts.
    /// Destructive interference dampens phase-opposed wavefronts.
    fn apply_interference(&mut self, new_vector: &[f32], importance: f32) {
        if self.wavefront_count() == 0 {
            return; // No existing wavefronts to interfere with
        }

        // Compute dot products between new vector and all existing wavefronts
        for i in 0..self.wavefront_count() {
            let existing_vector = self.wavefronts.row(i);
            let dot_product: f32 = existing_vector.iter()
                .zip(new_vector.iter())
                .map(|(a, b)| a * b)
                .sum();

            // Phase difference affects interference pattern
            let phase_diff = (self.phase[i] - 0.0).cos(); // New wavefront starts at phase 0
            let interference = dot_product * phase_diff * importance * 0.1; // Scale interference

            // Apply constructive/destructive interference
            self.energy[i] = (self.energy[i] + interference).max(0.0); // Energy can't go negative

            // Phase coupling — nearby vectors tend to align phases (Kuramoto-like)
            if dot_product.abs() > 0.5 { // High similarity threshold
                let coupling = 0.05;
                self.phase[i] += coupling * (0.0 - self.phase[i]).sin(); // Pull toward phase 0
            }
        }
    }

    /// Recall memories through resonance — query wave interferes with stored patterns.
    pub fn recall(&self, query: &str, top_k: usize, pipeline: &EncodingPipeline) -> Result<Vec<Resonance>, MediumError> {
        if self.wavefront_count() == 0 {
            return Ok(Vec::new());
        }

        // 1. Encode query as wave
        let query_vector = pipeline.encode_text(query)
            .map_err(|e| MediumError::Serialization(bincode::Error::from(std::io::Error::new(
                std::io::ErrorKind::InvalidData,
                format!("query encoding failed: {}", e)
            ))))?;

        // 2. Compute interference pattern — matrix multiplication H @ q
        let mut resonances = Vec::new();
        let effective_strengths = self.effective_strength(None);

        for i in 0..self.wavefront_count() {
            let wavefront = self.wavefronts.row(i);
            
            // Dot product (similarity)
            let similarity: f32 = wavefront.iter()
                .zip(query_vector.iter())
                .map(|(a, b)| a * b)
                .sum();

            // Modulate by wave dynamics (energy, phase, temporal decay)
            let effective_strength = effective_strengths[i];
            let phase_modulation = self.phase[i].cos(); // Phase affects resonance
            let resonance_strength = similarity * effective_strength * phase_modulation;

            resonances.push(Resonance {
                id: self.metadata[i].id,
                content: self.metadata[i].content.clone(),
                similarity,
                resonance_strength,
                effective_strength,
            });
        }

        // 3. Sort by resonance strength and return top-k
        resonances.sort_by(|a, b| b.resonance_strength.total_cmp(&a.resonance_strength));
        resonances.truncate(top_k);

        Ok(resonances)
    }

    /// Save the medium to a .hrm file.
    pub fn save<P: AsRef<Path>>(&self, path: P) -> Result<(), MediumError> {
        let file = File::create(path.as_ref())?;
        let mut writer = BufWriter::new(file);

        // Magic bytes
        writer.write_all(&HRM_MAGIC)?;

        // Version
        writer.write_all(&HRM_VERSION.to_le_bytes())?;

        // Timestamp
        let timestamp = Utc::now().timestamp_millis();
        writer.write_all(&timestamp.to_le_bytes())?;

        // Dimensions (N, D)
        let n = self.wavefront_count() as u32;
        let d = WAVEFRONT_DIM as u32;
        writer.write_all(&n.to_le_bytes())?;
        writer.write_all(&d.to_le_bytes())?;

        // Wavefronts tensor (row-major f32 array)
        for row in self.wavefronts.outer_iter() {
            for &val in row.iter() {
                writer.write_all(&val.to_le_bytes())?;
            }
        }

        // Energy, frequency, phase arrays
        for &val in self.energy.iter() {
            writer.write_all(&val.to_le_bytes())?;
        }
        for &val in self.frequency.iter() {
            writer.write_all(&val.to_le_bytes())?;
        }
        for &val in self.phase.iter() {
            writer.write_all(&val.to_le_bytes())?;
        }

        // Timestamps
        for &ts in &self.timestamps {
            writer.write_all(&ts.to_le_bytes())?;
        }

        // Metadata (bincode serialized)
        let metadata_bytes = bincode::serialize(&self.metadata)?;
        let metadata_len = metadata_bytes.len() as u32;
        writer.write_all(&metadata_len.to_le_bytes())?;
        writer.write_all(&metadata_bytes)?;

        // Consciousness state (computed on-the-fly)
        let consciousness = self.compute_consciousness();
        let consciousness_bytes = bincode::serialize(&consciousness)?;
        let consciousness_len = consciousness_bytes.len() as u32;
        writer.write_all(&consciousness_len.to_le_bytes())?;
        writer.write_all(&consciousness_bytes)?;

        // Checksum (blake3 of all preceding data)
        writer.flush()?;
        drop(writer);

        // Reopen to compute checksum
        let mut file = File::open(path.as_ref())?;
        let mut hasher = blake3::Hasher::new();
        std::io::copy(&mut file, &mut hasher)?;
        let checksum = hasher.finalize();

        // Append checksum
        let mut file = std::fs::OpenOptions::new()
            .append(true)
            .open(path.as_ref())?;
        file.write_all(checksum.as_bytes())?;

        Ok(())
    }

    /// Save the medium and commit to git with a message
    /// 
    /// This function:
    /// 1. Saves the .hrm file (using existing save() method)
    /// 2. Runs `git add <filename>` on the saved file  
    /// 3. Runs `git commit -m "<message>"`
    /// 4. Returns the commit hash
    /// 5. Optionally: `git push origin master` if push flag is set
    /// 
    /// # Arguments
    /// * `path` - Path to save the .hrm file
    /// * `message` - Git commit message
    /// * `push` - Whether to push to origin master after committing
    #[cfg(feature = "hrm")]
    pub fn save_and_commit<P: AsRef<Path>>(&self, path: P, message: &str, push: bool) -> Result<String, MediumError> {
        let path_ref = path.as_ref();
        
        // 1. Save the .hrm file
        self.save(path_ref)?;
        
        // 2. Git add the file
        let output = Command::new("git")
            .args(&["add", &path_ref.to_string_lossy()])
            .current_dir(path_ref.parent().unwrap_or(Path::new(".")))
            .output()
            .map_err(|e| MediumError::Git(format!("Failed to run git add: {}", e)))?;
        
        if !output.status.success() {
            return Err(MediumError::Git(format!(
                "git add failed: {}",
                String::from_utf8_lossy(&output.stderr)
            )));
        }
        
        // 3. Git commit with message
        let output = Command::new("git")
            .args(&["commit", "-m", message])
            .current_dir(path_ref.parent().unwrap_or(Path::new(".")))
            .output()
            .map_err(|e| MediumError::Git(format!("Failed to run git commit: {}", e)))?;
        
        if !output.status.success() {
            return Err(MediumError::Git(format!(
                "git commit failed: {}",
                String::from_utf8_lossy(&output.stderr)
            )));
        }
        
        // 4. Get the commit hash
        let output = Command::new("git")
            .args(&["rev-parse", "HEAD"])
            .current_dir(path_ref.parent().unwrap_or(Path::new(".")))
            .output()
            .map_err(|e| MediumError::Git(format!("Failed to get commit hash: {}", e)))?;
        
        if !output.status.success() {
            return Err(MediumError::Git(format!(
                "git rev-parse failed: {}",
                String::from_utf8_lossy(&output.stderr)
            )));
        }
        
        let commit_hash = String::from_utf8_lossy(&output.stdout).trim().to_string();
        
        // 5. Optional push to origin master
        if push {
            let output = Command::new("git")
                .args(&["push", "origin", "master"])
                .current_dir(path_ref.parent().unwrap_or(Path::new(".")))
                .output()
                .map_err(|e| MediumError::Git(format!("Failed to run git push: {}", e)))?;
            
            if !output.status.success() {
                // Push failure is non-fatal, just log it
                eprintln!("Warning: git push failed: {}", String::from_utf8_lossy(&output.stderr));
            }
        }
        
        Ok(commit_hash)
    }
    
